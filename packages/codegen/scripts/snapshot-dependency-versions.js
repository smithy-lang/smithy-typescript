/**
 * Writes the versions of the published workspace packages into a TypeScript module.
 * It runs as part of the build, so the snapshot reflects the versions at publish time.
 */
const fs = require("node:fs");
const path = require("node:path");

const packagesDir = path.join(__dirname, "..", "..");
const target = path.join(__dirname, "..", "src", "typescript", "DependencyVersionsSnapshot.ts");

const versions = {};
for (const entry of fs.readdirSync(packagesDir).sort()) {
  const file = path.join(packagesDir, entry, "package.json");
  if (!fs.existsSync(file)) {
    continue;
  }
  const json = JSON.parse(fs.readFileSync(file, "utf-8"));
  if (!json.private) {
    versions[json.name] = json.version;
  }
}

const lines = Object.entries(versions).map(
  ([name, version]) => `  ${JSON.stringify(name)}: ${JSON.stringify(version)},`
);
fs.writeFileSync(
  target,
  [
    "/**",
    " * Generated by scripts/snapshot-dependency-versions.js at build time. Do not edit.",
    " *",
    " * @internal",
    " */",
    "export const DEPENDENCY_VERSIONS: Readonly<Record<string, string>> = {",
    ...lines,
    "};",
    "",
  ].join("\n")
);
